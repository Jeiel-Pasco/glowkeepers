#!/usr/bin/env python3
"""Golden values that the game's Luau modules must reproduce (tests/golden.spec.luau).

Reads ../config/economy.json, the file the game and sim_v3.py read, and writes golden_odds.json:
rarity odds (the rarest-first roll used by sim.py and sim_v3.py), luck, rebirth thresholds,
upgrade and lure prices, and whole-night fire outcomes.

Each function below mirrors its Luau twin line for line (Roll.distribution, Economy.*,
Fire.simulate), so CI catches any drift between the sim's maths and the game's.
Pure Python, no numpy, so CI can run it anywhere.

    python sim/golden_odds.py           rewrite sim/golden_odds.json
    python sim/golden_odds.py --check   exit 1 if the file doesn't match the config
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CFG_PATH = os.path.join(HERE, "..", "config", "economy.json")
OUT_PATH = os.path.join(HERE, "golden_odds.json")

LUCKS = [1, 2, 5, 10, 30]  # TECH_SPEC §14
LUCK_SAMPLES = [(0, 0), (1, 0), (10, 2), (25, 5), (60, 12)]  # (lantern, stars)
REBIRTH_STARS = 31  # thresholds for Star 0..30


def rarity_distribution(cfg, luck, floor):
    """Roll.distribution: exact odds of each tier (1-based floor)."""
    rar, lk = cfg["rarities"], cfg["luck"]
    n = len(rar)
    probs = [0.0] * n
    remaining = 1.0
    for tier in range(n, floor, -1):
        p = 1 / rar[tier - 1]["oneIn"]
        if tier >= lk["appliesFromRarity"]:
            p = min(p * luck, lk["tierCap"])
        probs[tier - 1] = remaining * p
        remaining *= 1 - p
    probs[floor - 1] = remaining
    return probs


def luck_value(cfg, lantern, stars, fire_survived):
    """Economy.luck (sim_v3: luck() × fireSurvivedMult on the night after a survived fire)."""
    lk = cfg["luck"]
    luck = (1 + lk["perLanternLevel"] * lantern) * (1 + lk["perStar"] * stars)
    if fire_survived:
        luck *= lk["fireSurvivedMult"]
    return luck


def rebirth_requirement(cfg, stars):
    """Economy.rebirthRequirement == sim_v3 rebirth_req."""
    rb = cfg["rebirth"]
    if rb.get("stepEnabled") and stars > rb["stepAfterStar"]:
        s = rb["stepAfterStar"]
        return rb["baseRequirement"] * rb["growth"] ** s * rb["growthAfterStep"] ** (stars - s)
    return rb["baseRequirement"] * rb["growth"] ** stars


def upgrade_prices(cfg, upgrade_id):
    """Economy.upgradeCost for every level below the max (sim_v3 prices, floored)."""
    up = cfg["upgrades"][upgrade_id]
    top = up["max"] - up["start"] if upgrade_id == "slots" else up["max"]
    return [math.floor(up["baseCost"] * up["growth"] ** level) for level in range(top)]


def lure_prices(cfg):
    lures = cfg["lures"]
    return [math.floor(lures["baseCost"] * lures["growth"] ** (floor - 1)) for floor in range(1, lures["maxFloor"] + 1)]


def modifier_by_id(cfg, modifier_id):
    for modifier in cfg["cycle"]["nightModifiers"]:
        if modifier["id"] == modifier_id:
            return modifier
    raise KeyError(modifier_id)


def fire_simulate(cfg, players, feeds, modifier=None):
    """Fire.simulate: one whole night, constant drain between feeds."""
    f = cfg["fire"]
    mod = modifier or {}
    duration = cfg["cycle"]["nightSeconds"]
    drain = (f["drainBase"] + f["drainPerPlayer"] * max(0, players)) * mod.get("fireDrainMult", 1)
    level = min(f["max"], mod.get("fireStart", f["start"]))
    now = 0
    for t, kind in sorted(feeds, key=lambda feed: feed[0]):
        if t > duration:
            break
        t = max(t, now)
        before = level - drain * (t - now)
        if before <= 0:
            return {"survived": False, "level": 0, "lostAt": now + level / drain}
        level = min(f["max"], before + f[kind])
        now = t
    final = level - drain * (duration - now)
    if final <= 0:
        return {"survived": False, "level": 0, "lostAt": now + level / drain}
    return {"survived": True, "level": final}


# Distinct feed times only: same-time feeds near the 100% cap could be applied in either order.
FIRE_CASES = [
    ("1 player, 2 wood (GAME_SYSTEMS §12: survives)", 1, [[30, "wood"], [60, "wood"]], None),
    ("8 players, 8 wood (§12: loses)", 8, [[5 + 10 * i, "wood"] for i in range(8)], None),
    ("8 players, unfed (about 75 s)", 8, [], None),
    ("4 players, 3 wood + 1 shard", 4, [[20, "wood"], [50, "wood"], [80, "wood"], [100, "shard"]], None),
    ("8 players, Gusty, 10 wood", 8, [[5 + 10 * i, "wood"] for i in range(10)], "Gusty"),
    ("3 players, Starfall, unfed", 3, [], "Starfall"),
    ("1 player, 25 wood (hits the cap)", 1, [[1 + i, "wood"] for i in range(25)], None),
]


def build(cfg):
    out = {
        "_note": "Generated by sim/golden_odds.py from config/economy.json. Do not edit by hand.",
        "rarity": [
            {"luck": luck, "floor": floor, "probs": rarity_distribution(cfg, luck, floor)}
            for luck in LUCKS
            for floor in range(1, cfg["lures"]["maxFloor"] + 1)
        ],
        "luck": [
            {"lantern": lantern, "stars": stars, "fireSurvived": fire, "value": luck_value(cfg, lantern, stars, fire)}
            for lantern, stars in LUCK_SAMPLES
            for fire in (False, True)
        ],
        "rebirth": [rebirth_requirement(cfg, k) for k in range(REBIRTH_STARS)],
        "upgrades": {uid: upgrade_prices(cfg, uid) for uid in ("lantern", "boots", "slots")},
        "lures": lure_prices(cfg),
        "fire": [],
    }
    for name, players, feeds, modifier_id in FIRE_CASES:
        modifier = modifier_by_id(cfg, modifier_id) if modifier_id else None
        case = {"name": name, "players": players, "feeds": feeds, "modifier": modifier_id}
        case.update(fire_simulate(cfg, players, feeds, modifier))
        out["fire"].append(case)
    return out


def main():
    with open(CFG_PATH, encoding="utf-8") as f:
        cfg = json.load(f)
    text = json.dumps(build(cfg), indent=1) + "\n"
    if "--check" in sys.argv:
        try:
            with open(OUT_PATH, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print("sim/golden_odds.json is out of date. Run: python sim/golden_odds.py")
            sys.exit(1)
        print("sim/golden_odds.json is current")
        return
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT_PATH)}")


if __name__ == "__main__":
    main()
